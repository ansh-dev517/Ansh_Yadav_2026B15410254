print("Question: Write a program to calculate the average age of patients.")
ages = [25, 45, 12, 60, 32, 8, 70, 22, 55, 35]

total_age = sum(ages)
total_patients = len(ages)

average_age = total_age / total_patients

print("Average Age:", average_age)